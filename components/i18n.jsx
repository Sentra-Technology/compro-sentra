export const TRANSLATIONS = { ID, EN, ZH, KO, MS };

/* ============ Context & hook ============ */

const LanguageContext = React.createContext({
  lang: "ID",
  setLang: () => {},
  t: ID,
});

export function LanguageProvider({ children }) {
  const [lang, setLangState] = React.useState("ID");

  React.useEffect(() => {
    try {
      const saved = localStorage.getItem("sentra-lang");
      if (saved && TRANSLATIONS[saved]) setLangState(saved);
    } catch (e) {}
  }, []);

  const setLang = React.useCallback((code) => {
    if (!TRANSLATIONS[code]) return;
    setLangState(code);
    try { localStorage.setItem("sentra-lang", code); } catch (e) {}
  }, []);

  const value = React.useMemo(
    () => ({ lang, setLang, t: TRANSLATIONS[lang] || ID }),
    [lang, setLang]
  );

  return (
    <LanguageContext.Provider value={value}>
      {children}
    </LanguageContext.Provider>
  );
}

export function useLang() {
  return React.useContext(LanguageContext);
}
